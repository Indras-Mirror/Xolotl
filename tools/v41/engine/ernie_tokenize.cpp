uint8_t category_byte(uint32_t cp) {
    size_t lo = 0, hi = sizeof(kCatRanges) / sizeof(kCatRanges[0]);
    while (lo < hi) {
        const size_t mid = (lo + hi) / 2;
        if (cp > kCatRanges[mid].last) lo = mid + 1;
        else if (cp < kCatRanges[mid].first) hi = mid;
        else return kCatRanges[mid].byte;
    }
    return 0xD0;
}

uint8_t collapse_cp(uint32_t cp) { return cp < 0x80 ? (uint8_t) cp : category_byte(cp); }

// llama.cpp replaces every `\p{X}` in a pattern with the collapsed byte plus that class's ASCII ranges; inside
// an existing [...] it inserts the bare contents, outside it wraps them in one.
std::string collapse_regex(const std::string& expr) {
    struct Entry {
        const char* pat;
        std::string cls;
    };
    const Entry kMap[] = {
        {"\\p{N}", std::string(1, (char) 0xD1) + "0-9"},
        {"\\p{L}", std::string(1, (char) 0xD2) + "A-Za-z"},
        // k_ucat_map: !-# %-* ,-/ :-; ?-@ \[-\] _ \{ \}
        {"\\p{P}", std::string(1, (char) 0xD3) + "!-#%-*,-/:-;?-@\\[-\\]_\\{\\}"},
        {"\\p{M}", std::string(1, (char) 0xD4)},
        // k_ucat_map: \$ \+ <=> ^ ` \| ~
        {"\\p{S}", std::string(1, (char) 0xD5) + "\\$\\+<=>^`\\|~"},
    };
    std::string out;
    bool inside = false;
    for (size_t i = 0; i < expr.size(); ++i) {
        if (expr[i] == '[' && (i == 0 || expr[i - 1] != '\\')) {
            out += '[';
            inside = true;
            continue;
        }
        if (inside && expr[i] == ']' && expr[i - 1] != '\\') {
            out += ']';
            inside = false;
            continue;
        }
        if (expr[i] == '\\' && i + 3 < expr.size() && expr[i + 1] == 'p' && expr[i + 2] == '{') {
            const size_t close = expr.find('}', i + 3);
            if (close != std::string::npos && close <= i + 10) {
                const std::string pat = expr.substr(i, close - i + 1);
                bool replaced = false;
                for (const Entry& e : kMap) {
                    if (pat != e.pat) continue;
                    if (!inside) out += '[';
                    out += e.cls;
                    if (!inside) out += ']';
                    i = close;
                    replaced = true;
                    break;
                }
                if (replaced) continue;
            }
        }
        out += expr[i];
    }
    return out;
}

// The two regex patterns of LLAMA_VOCAB_PRE_TYPE_ERNIE5 (llama-vocab.cpp), transcribed as the GGUF's
// `tokenizer.ggml.pre = ernie5` selects them.
const char* const kDigitsPat = R"(\p{N}{1,3}(?=(?:\p{N}{3})*(?!\p{N})))";
const char* const kWordsPat =
    R"([!\"#$%&'()*+,\-./:;<=>?@\[\\\]^_`{|}~][A-Za-z]+|[^\r\n\p{L}\p{P}\p{S}]?[\p{L}\p{M}]+| ?[\p{P}\p{S}]+[\r\n]*|\s*[\r\n]+|\s+(?!\S)|\s+)";

// ---------------------------------------------------------------- splitting
// One pattern applied to every piece (`offsets` are piece lengths over the whole string): a match is a piece,
// the unmatched gaps between matches are pieces, exactly `unicode_regex_split_stl`.
std::vector<size_t> apply_regex(const std::string& s, const std::vector<size_t>& offsets, const std::regex& re) {
    std::vector<size_t> out;
    out.reserve(offsets.size() + 2);
    size_t start = 0;
    for (const size_t len : offsets) {
        const auto begin = s.begin() + (ptrdiff_t) start;
        size_t last = 0;
        for (std::sregex_iterator it(begin, begin + (ptrdiff_t) len, re), end; it != end; ++it) {
            const size_t pos = (size_t) it->position(), l = (size_t) it->length();
            if (pos > last) out.push_back(pos - last);
            out.push_back(l);
            last = pos + l;
        }
        if (last < len) out.push_back(len - last);
        start += len;
    }
    return out;
}

// The second pattern, `[一-龥぀-ゟ゠-ヿ]+` (Han + hiragana + katakana runs): hand-rolled because it is a
// codepoint-range class rather than a `\p{..}` one, and matching it on the collapsed text would erase the
// Han/kana distinction.  Same leftmost-greedy-runs semantics as the reference's std::wregex on codepoints.
std::vector<size_t> apply_cjk(const std::vector<uint32_t>& cpts, const std::vector<size_t>& offsets) {
    auto in_class = [](uint32_t c) {
        return (c >= 0x4E00 && c <= 0x9FA5) || (c >= 0x3040 && c <= 0x309F) || (c >= 0x30A0 && c <= 0x30FF);
    };
    std::vector<size_t> out;
    out.reserve(offsets.size() + 2);
    size_t start = 0;
    for (const size_t len : offsets) {
        size_t pos = 0;
        while (pos < len) {
            const bool in = in_class(cpts[start + pos]);
            const size_t s = pos;
            while (pos < len && in_class(cpts[start + pos]) == in) ++pos;
            out.push_back(pos - s);
        }
        start += len;
    }
    return out;
}

// ---------------------------------------------------------------- BPE
void bpe_piece(const ErnieTokenizer& tk, const std::string& piece, std::vector<int>& out) {
    std::vector<std::string> parts;
    parts.reserve(piece.size());
    // BYTE level: every byte of the piece's UTF-8, each through bytes_to_unicode.
    for (size_t i = 0; i < piece.size(); ++i) parts.push_back(tk.byte_char[(unsigned char) piece[i]]);
    while (parts.size() > 1) {
        int32_t best_rank = std::numeric_limits<int32_t>::max();
        size_t best = std::numeric_limits<size_t>::max();
        for (size_t i = 0; i + 1 < parts.size(); ++i) {
            std::string key = parts[i];
            key += '\x1f';
            key += parts[i + 1];
            const auto it = tk.merge_ranks.find(key);
            // lowest rank wins; the scan is left to right, so the leftmost pair of equal rank wins too
            if (it != tk.merge_ranks.end() && it->second < best_rank) {
                best_rank = it->second;
                best = i;
            }
        }
        if (best == std::numeric_limits<size_t>::max()) break;
        parts[best] += parts[best + 1];
        parts.erase(parts.begin() + (ptrdiff_t) best + 1);
    }
    for (const std::string& tok : parts) {
        const auto it = tk.ids.find(tok);
        if (it == tk.ids.end()) throw std::runtime_error("BPE produced a token outside the vocabulary");
        out.push_back(it->second);
    }
}

// `_encode_plain`: pre-split, then BPE each piece.
void encode_plain(const ErnieTokenizer& tk, const std::string& text, std::vector<int>& out) {
    if (text.empty()) return;
    const std::vector<uint32_t> cpts = utf8_cpts(text);
    std::string collapsed;
    collapsed.reserve(cpts.size());
    for (const uint32_t cp : cpts) collapsed.push_back((char) collapse_cp(cp));
    std::vector<size_t> offsets{cpts.size()};
    offsets = apply_regex(collapsed, offsets, tk.re_digits);
    offsets = apply_cjk(cpts, offsets);
    offsets = apply_regex(collapsed, offsets, tk.re_words);
    std::string piece;
    size_t start = 0;
    for (const size_t len : offsets) {
        if (len) {
            piece.clear();
            for (size_t i = 0; i < len; ++i) append_utf8(piece, cpts[start + i]);
            bpe_piece(tk, piece, out);
        }
        start += len;
    }
}

// ---------------------------------------------------------------- GGUF tokenizer arrays
// GgufFile keeps only the first 64 entries of a metadata array (`read_value` samples it), so the four
// tokenizer keys are re-read here from the same metadata shard with a small sequential cursor.
struct KvReader {
    std::FILE* f = nullptr;
    bool ok = true;

    template <class T>
    T get() {
        T v{};
        if (ok && std::fread(&v, sizeof(T), 1, f) != 1) ok = false;
        return v;
    }
    std::string str() {
        const uint64_t n = get<uint64_t>();
        if (!ok) return {};
        if (n > (1ull << 31)) {
            ok = false;
            return {};
        }
        std::string s((size_t) n, '\0');
        if (n && std::fread(&s[0], 1, (size_t) n, f) != (size_t) n) ok = false;
        return s;
    }
    void skip(uint64_t n) {
        if (ok && std::fseek(f, (long) n, SEEK_CUR) != 0) ok = false;
    }
};

int fixed_size(uint32_t t) {
    switch (t) {
    case 0: case 1: case 7: return 1;        // U8 I8 BOOL
    case 2: case 3: return 2;                // U16 I16
    case 4: case 5: case 6: return 4;        // U32 I32 F32
    case 10: case 11: case 12: return 8;     // U64 I64 F64
    default: return 0;
    }
}

bool skip_value(KvReader& r, uint32_t t, int depth = 0) {
    if (depth > 2) return false;
    if (const int fs = fixed_size(t)) {
        r.skip((uint64_t) fs);
        return r.ok;
    }
    if (t == 8) {                            // STRING
        r.str();
        return r.ok;
    }
    if (t == 9) {                            // ARRAY
        const uint32_t elem = r.get<uint32_t>();
        const uint64_t n = r.get<uint64_t>();
        if (!r.ok) return false;
        if (const int fs = fixed_size(elem)) {
            r.skip(n * (uint64_t) fs);
            return r.ok;
        }
        if (n > (1ull << 24)) return false;
        for (uint64_t i = 0; i < n && r.ok; ++i)
            if (!skip_value(r, elem, depth + 1)) return false;
        return r.ok;
    }
    return false;
}

bool read_str_array(KvReader& r, std::vector<std::string>& out) {
    const uint32_t elem = r.get<uint32_t>();
    const uint64_t n = r.get<uint64_t>();
    if (!r.ok || elem != 8 || n > (1ull << 24)) return false;
    out.clear();
    out.reserve((size_t) n);
    for (uint64_t i = 0; i < n && r.ok; ++i) out.push_back(r.str());
    return r.ok;
}

bool read_int_array(KvReader& r, std::vector<int32_t>& out) {
    const uint32_t elem = r.get<uint32_t>();
    const uint64_t n = r.get<uint64_t>();
    if (!r.ok || n > (1ull << 24)) return false;
    out.assign((size_t) n, 0);
    for (uint64_t i = 0; i < n && r.ok; ++i) {
        switch (elem) {
        case 0: out[(size_t) i] = (int32_t) r.get<uint8_t>(); break;
        case 1: out[(size_t) i] = (int32_t) r.get<int8_t>(); break;
        case 2: out[(size_t) i] = (int32_t) r.get<uint16_t>(); break;
        case 3: out[(size_t) i] = (int32_t) r.get<int16_t>(); break;
        case 4: out[(size_t) i] = (int32_t) r.get<uint32_t>(); break;
        case 5: out[(size_t) i] = r.get<int32_t>(); break;
        case 10: out[(size_t) i] = (int32_t) r.get<uint64_t>(); break;
        case 11: out[(size_t) i] = (int32_t) r.get<int64_t>(); break;
        default: r.ok = false; break;
        }
    }
    return r.ok;
}

bool read_tokenizer_arrays(const std::string& path, std::vector<std::string>& tokens,
                           std::vector<std::string>& merges, std::vector<int32_t>& types, std::string& err) {
    std::FILE* f = std::fopen(path.c_str(), "rb");
    if (!f) {
        err = "cannot open " + path;
        return false;
    }
    KvReader r{f};
    const uint32_t magic = r.get<uint32_t>();
    const uint32_t version = r.get<uint32_t>();
    const uint64_t n_tensors = r.get<uint64_t>();
    const uint64_t n_kv = r.get<uint64_t>();
    (void) n_tensors;
    if (!r.ok || magic != 0x46554747u || version != 3) {
        std::fclose(f);
        err = "not a GGUF v3 file: " + path;
        return false;
    }
    bool have_tokens = false, have_merges = false;
    for (uint64_t i = 0; i < n_kv && r.ok; ++i) {
        const std::string key = r.str();
        const uint32_t t = r.get<uint32_t>();
        if (!r.ok) break;
        if (key == "tokenizer.ggml.tokens" && t == 9) have_tokens = read_str_array(r, tokens);
        else if (key == "tokenizer.ggml.merges" && t == 9) have_merges = read_str_array(r, merges);
        else if (key == "tokenizer.ggml.token_type" && t == 9) read_int_array(r, types);
        else if (!skip_value(r, t)) r.ok = false;
    }
    std::fclose(f);
    if (!r.ok) {
        err = "truncated or malformed GGUF metadata in " + path;
        return false;
    }
    if (!have_tokens || !have_merges || tokens.empty()) {
        err = "GGUF is missing tokenizer.ggml.tokens / tokenizer.ggml.merges";
        return false;
    }
    return true;
}

