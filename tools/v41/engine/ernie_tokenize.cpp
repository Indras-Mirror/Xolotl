bool ernie_tokenizer_load(const std::string& gguf, ErnieTokenizer& tk, std::string& err) {
    tk = ErnieTokenizer();
    std::unique_ptr<GgufModel> model;
    try {
        model.reset(new GgufModel(GgufModel::open(gguf)));
    } catch (const std::exception& e) {
        err = std::string("GGUF: ") + e.what();
        return false;
    }
    const GgufFile& mf = model->meta();
    auto meta_str = [&](const char* key, std::string& out) {
        const MetaValue* v = mf.get(key);
        if (!v || v->type != MetaType::STRING) return false;
        out = v->s;
        return true;
    };
    std::string model_kind, pre;
    if (!meta_str("tokenizer.ggml.model", model_kind) || model_kind != "gpt2") {
        err = "expected a byte-level BPE tokenizer (tokenizer.ggml.model = 'gpt2')";
        return false;
    }
    if (!meta_str("tokenizer.ggml.pre", pre)) pre = "qwen35";   // the Python reference's default, then refused
    if (pre != "ernie5") {
        err = "unsupported tokenizer.ggml.pre '" + pre + "' (this encoder implements 'ernie5')";
        return false;
    }
    tk.pre = pre;
    if (const MetaValue* b = mf.get("tokenizer.ggml.bos_token_id"))
        if (b->is_num()) tk.bos_id = (int32_t) b->u;

    if (!read_tokenizer_arrays(model->shard(0).path(), tk.tokens, tk.merges, tk.token_types, err)) return false;

    // ---- the vocabulary and the merge ranks ----
    tk.ids.reserve(tk.tokens.size() * 2);
    for (size_t i = 0; i < tk.tokens.size(); ++i) {
        if (!tk.ids.emplace(tk.tokens[i], (int32_t) i).second) {
            err = "vocabulary has a duplicate token: " + tk.tokens[i];
            return false;
        }
    }
    tk.merge_ranks.reserve(tk.merges.size() * 2);
    for (size_t i = 0; i < tk.merges.size(); ++i) {
        const std::string& m = tk.merges[i];
        const size_t sp = m.find(' ');
        if (sp == std::string::npos || m.find(' ', sp + 1) != std::string::npos) {
            err = "merge " + std::to_string(i) + " is not a pair";
            return false;
        }
        const std::string left = m.substr(0, sp), right = m.substr(sp + 1);
        if (!tk.ids.count(left) || !tk.ids.count(right)) {
            err = "merge " + std::to_string(i) + " names a token outside the vocabulary";
            return false;
        }
        // the reference's dict assignment: the last occurrence of a pair owns the rank
        tk.merge_ranks[left + '\x1f' + right] = (int32_t) i;
    }

    // ---- the literals matched instead of being BPE'd (GGUF token types: 3 CONTROL, 4 USER_DEFINED) ----
    for (size_t i = 0; i < tk.token_types.size() && i < tk.tokens.size(); ++i) {
        if (tk.token_types[i] == 4) {
            tk.always_literals.emplace_back(tk.tokens[i], (int32_t) i);
            tk.special_literals.emplace_back(tk.tokens[i], (int32_t) i);
        } else if (tk.token_types[i] == 3) {
            tk.special_literals.emplace_back(tk.tokens[i], (int32_t) i);
        }
    }
    auto longer_first = [](const std::pair<std::string, int32_t>& a, const std::pair<std::string, int32_t>& b) {
        return a.first.size() > b.first.size();
    };
    std::stable_sort(tk.always_literals.begin(), tk.always_literals.end(), longer_first);
    std::stable_sort(tk.special_literals.begin(), tk.special_literals.end(), longer_first);

    // ---- the GPT-2 byte alphabet, both directions ----
    tk.cp_to_byte.fill(-1);
    bool printable[256] = {false};
    for (int b = 33; b <= 126; ++b) printable[b] = true;
    for (int b = 161; b <= 172; ++b) printable[b] = true;
    for (int b = 174; b <= 255; ++b) printable[b] = true;
    uint32_t next = 256;
    for (int b = 0; b < 256; ++b) {
        const uint32_t cp = printable[b] ? (uint32_t) b : next++;
        tk.byte_char[b].clear();
        append_utf8(tk.byte_char[b], cp);
        if (cp < tk.cp_to_byte.size()) tk.cp_to_byte[cp] = b;
    }

    // ---- the pre-tokenizer patterns, on the collapsed alphabet ----
    try {
        const auto flags = std::regex::ECMAScript | std::regex::optimize | std::regex::nosubs;
        tk.re_digits = std::regex(collapse_regex(kDigitsPat), flags);
        tk.re_words = std::regex(collapse_regex(kWordsPat), flags);
    } catch (const std::regex_error& e) {
        err = std::string("pre-tokenizer regex: ") + e.what();
        return false;
    }
    return true;
}

std::vector<int> ernie_tokenizer_encode(const ErnieTokenizer& tk, const std::string& text, bool parse_special) {
    const auto& literals = parse_special ? tk.special_literals : tk.always_literals;
    std::vector<int> out;
    if (literals.empty()) {
        encode_plain(tk, text, out);
        return out;
    }
    // The literals matched on the RAW text (a special token's string is matched, not decomposed), leftmost
    // first, longest alternative first (the reference sorts by length, reverse).
    size_t pos = 0, plain_from = 0;
    while (pos < text.size()) {
        const std::pair<std::string, int32_t>* hit = nullptr;
        for (const auto& lit : literals) {
            if (text.compare(pos, lit.first.size(), lit.first) == 0) {
                hit = &lit;
                break;
            }
        }
        if (hit) {
            if (pos > plain_from) encode_plain(tk, text.substr(plain_from, pos - plain_from), out);
            out.push_back(hit->second);
            pos += hit->first.size();
            plain_from = pos;
        } else {
            ++pos;
        }
    }
    if (plain_from < text.size()) encode_plain(tk, text.substr(plain_from), out);
    return out;
}

std::string ernie_tokenizer_decode(const ErnieTokenizer& tk, const std::vector<int>& ids) {
    std::string out;
    for (const int id : ids) {
        if (id < 0 || (size_t) id >= tk.tokens.size())
            throw std::runtime_error("token id " + std::to_string(id) + " is outside the vocabulary");
        const size_t i = (size_t) id;
        const bool special = i < tk.token_types.size() && (tk.token_types[i] == 3 || tk.token_types[i] == 4);
        if (special) {   // a special token's string is the literal text
            out += tk.tokens[i];
            continue;
        }
        for (const uint32_t cp : utf8_cpts(tk.tokens[i])) {
            if (cp >= tk.cp_to_byte.size() || tk.cp_to_byte[cp] < 0)
                throw std::runtime_error("token " + std::to_string(id) + " contains a character outside the byte alphabet");
            out.push_back((char) tk.cp_to_byte[cp]);
        }
    }
    return out;
}

